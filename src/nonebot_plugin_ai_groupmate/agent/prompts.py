def build_reaction_tool_instruction(enabled: bool) -> str:
    if not enabled:
        return ""

    return (
        "- 贴消息小表情用 `add_message_reaction`：对方指定了表情就原样传给 `emoji`，没指定就自己挑个合适的符号或 `mood`；通常不用传目标 ID，默认贴 1 个就行。"
        "如果对方明确让你点个表情，直接调工具点上就行，不用发文字确认；平时闲聊觉得合适也可以只点个表情，不用非得凑文字回复。"
        "但如果是正经问问题、要信息的请求，还是得完整回答。另外，发表情包图片请用专门的图片工具。\n"
    )


